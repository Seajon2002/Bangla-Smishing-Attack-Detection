class PhishingDetector(nn.Module):
    def __init__(self, meta_dim=META_DIM):
        super().__init__()

        self.xlm    = AutoModel.from_pretrained("xlm-roberta-base")
        self.bangla = AutoModel.from_pretrained("csebuetnlp/banglabert")

        self.meta_encoder = nn.Sequential(
            nn.Linear(meta_dim, 64),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(64, 64),
            nn.ReLU(),
        )

        self.attn_pool1 = nn.Linear(768, 1)
        self.attn_pool2 = nn.Linear(768, 1)

        fusion_dim = 768 + 768 + 64
        self.classifier = nn.Sequential(
            nn.Linear(fusion_dim, 512),
            nn.GELU(),
            nn.Dropout(0.4),
            nn.Linear(512, 128),
            nn.GELU(),
            nn.Dropout(0.2),
            nn.Linear(128, 2),
        )

    def _weighted_pool(self, hidden, attn_layer):
        weights = torch.softmax(attn_layer(hidden), dim=1)
        return (hidden * weights).sum(dim=1)

    def forward(self, ids1, mask1, ids2, mask2, meta):
        h1 = self.xlm(ids1,    attention_mask=mask1).last_hidden_state
        h2 = self.bangla(ids2, attention_mask=mask2).last_hidden_state
        o1 = self._weighted_pool(h1, self.attn_pool1)
        o2 = self._weighted_pool(h2, self.attn_pool2)
        m  = self.meta_encoder(meta)
        x  = torch.cat([o1, o2, m], dim=1)
        return self.classifier(x)



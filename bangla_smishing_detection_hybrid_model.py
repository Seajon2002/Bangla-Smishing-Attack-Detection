def clean_text(text):
    text = str(text).lower()
    text = re.sub(r'https?://[^\s]+', ' [URL] ', text)
    text = re.sub(r'www\.[^\s]+',     ' [URL] ', text)
    text = re.sub(r'\s+', ' ', text).strip()
    return text


def add_text_features(df):
    df['len']         = df['text'].apply(len)
    df['word_count']  = df['text'].apply(lambda x: len(x.split()))
    df['digits']      = df['text'].apply(lambda x: sum(c.isdigit() for c in x))
    df['special']     = df['text'].apply(lambda x: len(re.findall(r'[!@#\$%\^&\*]', x)))
    df['upper_ratio'] = df['text_raw'].apply(
        lambda x: sum(c.isupper() for c in str(x)) / max(len(str(x)), 1)
    )
    return df


def load_and_preprocess(path):
    print("📂 Loading dataset...")
    df = pd.read_csv(path)

    # ── FIX 1: প্রথমেই NaN drop ──
    df = df.dropna(subset=['text', 'label'])
    df = df.reset_index(drop=True)

    # Normalize labels
    df['label'] = df['label'].astype(str).str.lower().str.strip()
    df = df[~df['label'].isin(['promo', 'promotion', 'promotional'])]
    df['label'] = df['label'].replace({
        'smish':    'spam', 'smishing': 'spam',
        'phishing': 'spam', 'fraud':    'spam',
        'normal':   'ham',
    })
    df = df[df['label'].isin(['spam', 'ham'])].copy()
    df = df.reset_index(drop=True)

    # Raw text
    df['text_raw'] = df['text'].copy()
    df['text']     = df['text'].apply(clean_text)
    df.drop_duplicates(subset=['text'], inplace=True)
    df = df.reset_index(drop=True)

    # ── FIX 2: target সঠিকভাবে তৈরি ──
    df['target'] = df['label'].map({'spam': 1, 'ham': 0})
    df = df.dropna(subset=['target'])
    df['target'] = df['target'].astype(int)

    # Text features
    df = add_text_features(df)

    # URL features
    print("🔗 Extracting URL features (একটু সময় লাগবে)...")
    url_feat_df = df['text_raw'].apply(
        lambda x: pd.Series(extract_sms_url_features(x))
    )
    df = pd.concat([df.reset_index(drop=True), url_feat_df], axis=1)

    # ── FIX 3: সব NaN fill ──
    df = df.fillna(0)
    df = df.reset_index(drop=True)

    print(f"✅ Dataset loaded: {len(df)} samples | "
          f"Spam: {df['target'].sum()} | Ham: {(df['target']==0).sum()}")
    return df



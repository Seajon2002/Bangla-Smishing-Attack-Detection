class SMSDataset(Dataset):
    def __init__(self, df, max_length=256):
        self.texts   = df['text'].values
        self.labels  = df['target'].values.astype(int)
        self.meta    = df[META_COLS].fillna(0).values.astype(np.float32)
        self.max_len = max_length

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx):
        t  = self.texts[idx]
        e1 = tok1(t, padding='max_length', truncation=True,
                  max_length=self.max_len, return_tensors='pt')
        e2 = tok2(t, padding='max_length', truncation=True,
                  max_length=self.max_len, return_tensors='pt')
        return {
            'ids1':  e1['input_ids'].squeeze(),
            'mask1': e1['attention_mask'].squeeze(),
            'ids2':  e2['input_ids'].squeeze(),
            'mask2': e2['attention_mask'].squeeze(),
            'meta':  torch.tensor(self.meta[idx], dtype=torch.float),
            'label': torch.tensor(self.labels[idx], dtype=torch.long),
        }


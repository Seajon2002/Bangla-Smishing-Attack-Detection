def analyze_url(url):
    features = {
        'domain_length':        0,
        'subdomain_count':      0,
        'has_digits_in_domain': 0,
        'is_https':             0,
        'suspicious_tld':       0,
        'brand_impersonation':  0,
        'has_at_symbol':        0,
        'has_ip':               0,
        'suspicious_path':      0,
        'is_short_url':         0,
        'path_length':          0,
        'query_length':         0,
        'special_char_count':   0,
    }
    try:
        parsed = urlparse(url)
        domain = parsed.netloc.lower()
        path   = parsed.path.lower()
        query  = parsed.query.lower()

        features['domain_length']        = len(domain)
        features['subdomain_count']      = max(0, domain.count('.') - 1)
        features['has_digits_in_domain'] = int(any(c.isdigit() for c in domain))
        features['is_https']             = int(parsed.scheme == 'https')
        features['suspicious_tld']       = int(any(domain.endswith(t) for t in SUSPICIOUS_TLDS))
        features['brand_impersonation']  = int(any(b in domain for b in BRAND_NAMES))
        features['has_at_symbol']        = int('@' in url)
        features['has_ip']               = int(bool(re.match(r'\d+\.\d+\.\d+\.\d+', domain)))
        features['suspicious_path']      = int(any(kw in path for kw in SUSPICIOUS_KEYWORDS))
        features['is_short_url']         = int(any(s in domain for s in SHORT_URL_DOMAINS))
        features['path_length']          = len(path)
        features['query_length']         = len(query)
        features['special_char_count']   = len(re.findall(r'[%\-_=&?]', url))
    except Exception:
        pass
    return features


def get_url_risk_score(url_features):
    score = (
        url_features.get('suspicious_tld',      0) * 2.0 +
        url_features.get('brand_impersonation',  0) * 3.0 +
        url_features.get('has_ip',               0) * 3.0 +
        url_features.get('has_at_symbol',        0) * 2.5 +
        url_features.get('suspicious_path',      0) * 1.5 +
        url_features.get('is_short_url',         0) * 1.0 +
        url_features.get('has_digits_in_domain', 0) * 0.5 +
        min(url_features.get('subdomain_count',  0) * 0.5, 2.0)
    )
    return min(score, 10.0)


def extract_sms_url_features(text):
    urls        = URL_PATTERN.findall(str(text))
    url_strings = [u[0] if isinstance(u, tuple) else u for u in urls]

    if not url_strings:
        return {
            'has_url': 0, 'url_count': 0, 'max_url_risk': 0.0,
            'has_short_url': 0, 'has_suspicious_url': 0,
            'has_ip_url': 0, 'has_brand_impersonation': 0,
            'total_url_special_chars': 0,
        }

    all_features = [analyze_url(u) for u in url_strings]
    risk_scores  = [get_url_risk_score(f) for f in all_features]

    return {
        'has_url':                 1,
        'url_count':               len(url_strings),
        'max_url_risk':            float(max(risk_scores)),
        'has_short_url':           int(any(f['is_short_url']        for f in all_features)),
        'has_suspicious_url':      int(any(f['suspicious_path']     for f in all_features)),
        'has_ip_url':              int(any(f['has_ip']              for f in all_features)),
        'has_brand_impersonation': int(any(f['brand_impersonation'] for f in all_features)),
        'total_url_special_chars': int(sum(f['special_char_count']  for f in all_features)),
    }


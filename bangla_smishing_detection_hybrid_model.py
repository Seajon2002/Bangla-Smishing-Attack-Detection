def check_google_safe_browsing(urls, api_key):
    if not api_key:
        return {}
    payload = {
        "client":     {"clientId": "sms-phishing-detector", "clientVersion": "1.0"},
        "threatInfo": {
            "threatTypes":      ["MALWARE", "SOCIAL_ENGINEERING",
                                 "UNWANTED_SOFTWARE", "POTENTIALLY_HARMFUL_APPLICATION"],
            "platformTypes":    ["ANY_PLATFORM"],
            "threatEntryTypes": ["URL"],
            "threatEntries":    [{"url": u} for u in urls],
        }
    }
    try:
        resp    = requests.post(
            f"https://safebrowsing.googleapis.com/v4/threatMatches:find?key={api_key}",
            json=payload, timeout=10
        )
        data    = resp.json()
        matches = data.get('matches', [])
        result  = {u: {'is_dangerous': False, 'threat_type': 'SAFE'} for u in urls}
        for m in matches:
            url = m['threat']['url']
            if url in result:
                result[url] = {
                    'is_dangerous': True,
                    'threat_type':  m.get('threatType', 'UNKNOWN'),
                }
        return result
    except Exception as e:
        print(f"⚠️ Google Safe Browsing error: {e}")
        return {}


def check_virustotal(url, api_key):
    if not api_key:
        return {'is_phishing': False, 'malicious_count': 0, 'total_engines': 0}
    try:
        headers = {"x-apikey": api_key}
        r1      = requests.post(
            "https://www.virustotal.com/api/v3/urls",
            headers=headers, data={"url": url}, timeout=15
        )
        scan_id = r1.json()['data']['id']
        r2      = requests.get(
            f"https://www.virustotal.com/api/v3/analyses/{scan_id}",
            headers=headers, timeout=15
        )
        stats = r2.json()['data']['attributes']['stats']
        mal   = stats.get('malicious', 0)
        total = sum(stats.values())
        return {'is_phishing': mal > 3, 'malicious_count': mal, 'total_engines': total}
    except Exception as e:
        print(f"⚠️ VirusTotal error: {e}")
        return {'is_phishing': False, 'malicious_count': 0, 'total_engines': 0}


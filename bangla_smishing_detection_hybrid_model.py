def run_epoch(loader, train=True):
    if train:
        model.train()
    else:
        model.eval()

    total_loss, all_probs, all_labels = 0.0, [], []

    ctx = torch.enable_grad() if train else torch.no_grad()
    with ctx:
        for batch in tqdm(loader, desc="Train" if train else "Eval", leave=False):
            ids1   = batch['ids1'].to(DEVICE)
            mask1  = batch['mask1'].to(DEVICE)
            ids2   = batch['ids2'].to(DEVICE)
            mask2  = batch['mask2'].to(DEVICE)
            meta   = batch['meta'].to(DEVICE)
            labels = batch['label'].to(DEVICE)

            logits = model(ids1, mask1, ids2, mask2, meta)
            loss   = criterion(logits, labels)

            if train:
                optimizer.zero_grad()
                loss.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
                optimizer.step()
                scheduler.step()

            total_loss += loss.item()
            probs = torch.softmax(logits, dim=1)[:, 1]
            all_probs.extend(probs.detach().cpu().numpy())
            all_labels.extend(labels.cpu().numpy())

    return total_loss / len(loader), np.array(all_probs), np.array(all_labels)



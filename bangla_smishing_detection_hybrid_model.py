def predict_sms(text, threshold=None, verbose=True):
    if threshold is None:
        threshold = best_thresh

    model.eval()
    reasons = []

    # Step 1: ML model
    clean     = clean_text(text)
    url_feats = extract_sms_url_features(text)

    meta_vals = np.array([[
        len(clean),
        len(clean.split()),
        sum(c.isdigit() for c in clean),
        len(re.findall(r'[!@#\$%\^&\*]', clean)),
        sum(c.isupper() for c in text) / max(len(text), 1),
        url_feats['has_url'],
        url_feats['url_count'],
        url_feats['max_url_risk'],
        url_feats['has_short_url'],
        url_feats['has_suspicious_url'],
        url_feats['has_ip_url'],
        url_feats['has_brand_impersonation'],
        url_feats['total_url_special_chars'],
    ]], dtype=np.float32)

    e1 = tok1(clean, padding='max_length', truncation=True,
              max_length=CONFIG["max_length"], return_tensors='pt')
    e2 = tok2(clean, padding='max_length', truncation=True,
              max_length=CONFIG["max_length"], return_tensors='pt')

    with torch.no_grad():
        logits = model(
            e1['input_ids'].to(DEVICE),
            e1['attention_mask'].to(DEVICE),
            e2['input_ids'].to(DEVICE),
            e2['attention_mask'].to(DEVICE),
            torch.tensor(meta_vals).to(DEVICE),
        )
        prob = torch.softmax(logits, dim=1)[0, 1].item()

    if prob > threshold:
        reasons.append(f"ML model confidence: {prob:.1%}")

    # Step 2: URL analysis
    urls        = URL_PATTERN.findall(text)
    url_strings = [u[0] if isinstance(u, tuple) else u for u in urls]
    url_details = []

    for url in url_strings:
        feats = analyze_url(url)
        risk  = get_url_risk_score(feats)
        url_details.append({'url': url, 'risk': risk, 'features': feats})

        if feats['brand_impersonation']:
            reasons.append(f"⚠️  Brand impersonation in URL: {url}")
        if feats['has_ip']:
            reasons.append(f"⚠️  IP-address URL: {url}")
        if feats['is_short_url']:
            reasons.append(f"⚠️  Shortened URL: {url}")
        if feats['suspicious_tld']:
            reasons.append(f"⚠️  Suspicious domain extension: {url}")
        if feats['suspicious_path']:
            reasons.append(f"⚠️  Suspicious path keywords: {url}")
        if feats['has_at_symbol']:
            reasons.append(f"⚠️  @ symbol in URL (phishing trick): {url}")

    # Step 3: Google Safe Browsing
    gsb_results = {}
    if url_strings and CONFIG["google_safebrowsing_key"]:
        gsb_results = check_google_safe_browsing(
            url_strings, CONFIG["google_safebrowsing_key"]
        )
        for url, res in gsb_results.items():
            if res['is_dangerous']:
                reasons.append(
                    f"🚨 Google Safe Browsing [{res['threat_type']}]: {url}"
                )

    # Step 4: VirusTotal
    vt_results = {}
    if url_strings and CONFIG["virustotal_key"]:
        for url in url_strings[:2]:
            vt = check_virustotal(url, CONFIG["virustotal_key"])
            vt_results[url] = vt
            if vt['is_phishing']:
                reasons.append(
                    f"🚨 VirusTotal: {vt['malicious_count']}/{vt['total_engines']} "
                    f"flagged: {url}"
                )

    is_phishing = (prob > threshold) or bool(reasons)
    verdict     = "🚨 PHISHING / SPAM" if is_phishing else "✅ SAFE (HAM)"

    result = {
        'verdict':     verdict,
        'ml_prob':     prob,
        'threshold':   threshold,
        'is_phishing': is_phishing,
        'reasons':     reasons,
        'urls_found':  url_strings,
        'url_details': url_details,
        'gsb_results': gsb_results,
        'vt_results':  vt_results,
    }

    if verbose:
        print("\n" + "="*60)
        print("🔍 SMS PHISHING ANALYSIS REPORT")
        print("="*60)
        print(f"📱 SMS      : {text[:120]}{'...' if len(text) > 120 else ''}")
        print(f"🤖 ML Score : {prob:.1%}  (threshold={threshold:.2f})")
        print(f"🔗 URLs     : {len(url_strings)} found → {url_strings}")
        print(f"\n📋 VERDICT  : {verdict}")
        if reasons:
            print("\n⚠️  Reasons:")
            for r in reasons:
                print(f"   • {r}")
        if url_details:
            print("\n🔗 URL Risk Scores:")
            for d in url_details:
                print(f"   [{d['risk']:.1f}/10] {d['url']}")
        print("="*60)

    return result


